"""Mailer box — sheet-hyperobjects cartridge (Pliego).

One family: the one-piece mailers with a hinged lid, from inside dimensions.

- ``style = "mailer"``: roll-end tuck-front mailer (FEFCO 0427 style) — the end walls are
  double: each rolls over the ears of the front and back walls and drops two lock tabs into
  slots cut through the base folds; the lid has dust flaps and a front tuck;
- ``style = "pizza"``: the front wall rolls instead and locks with three tabs; the side walls
  carry corner ears.

Generated by ``pliego.dieline.mailer`` (panels inside + caliper, rolled inner leaves t shorter,
slots 2t across the folds). Kinematic fold program; the preview keeps the base on the table (the
first end wall starts pre-rolled when the sheet's first face is on it). Optional brand artwork
on the lid's print side (``assets/brand-mark.svg``, original placeholder art).
"""

import pliego


def PARAM(get, default):
    try:
        return get()
    except NameError:
        return default


style = str(PARAM(lambda: style, "mailer"))           # noqa: F821
length = float(PARAM(lambda: length, 250.0))          # noqa: F821
width = float(PARAM(lambda: width, 180.0))            # noqa: F821
depth = float(PARAM(lambda: depth, 60.0))             # noqa: F821
board = str(PARAM(lambda: board, "corrugated-e-flute"))   # noqa: F821
branding = bool(PARAM(lambda: branding, True))        # noqa: F821

BOARDS = ("corrugated-f-flute", "corrugated-e-flute", "corrugated-b-flute")
if board not in BOARDS:
    raise ValueError(f"mailer-box: board must be one of {BOARDS}, got {board!r}")
if style not in ("mailer", "pizza"):
    raise ValueError(f"mailer-box: style must be mailer or pizza, got {style!r}")
width = min(width, length)
depth = min(depth, width)

pack = pliego.dieline.mailer(length, width, depth, board,
                             roll="ends" if style == "mailer" else "front")

artwork = []
if branding:
    xs = [p[0] for p in pack.panels["lid"].polygon]
    ys = [p[1] for p in pack.panels["lid"].polygon]
    side = 0.45 * min(max(xs) - min(xs), max(ys) - min(ys))
    cx, cy = (min(xs) + max(xs)) / 2.0, (min(ys) + max(ys)) / 2.0
    artwork.append(pliego.press.artwork(
        "brand-mark", pack.sheet, "assets/brand-mark.svg", (cx - side / 2.0, cy - side / 2.0),
        (side, side), side="front", panel="lid", clip="panel"))

result = pliego.dieline.assemble(
    [pack], title=f"Mailer box ({style})", artwork=artwork,
    label={"en": "Fold program", "es": "Secuencia de armado", "fr": "Séquence de montage",
           "pt": "Sequência de montagem"},
    meta={"cartridge": "mailer-box",
          "params": {"style": style, "length": length, "width": width, "depth": depth,
                     "board": board, "branding": branding}})
