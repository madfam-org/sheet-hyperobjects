"""Corrugated shipper — sheet-hyperobjects cartridge (Pliego).

One family: the slotted shipping cases cut from one corrugated blank, from inside dimensions.

- mode ``slotted``: ``style`` = regular slotted (FEFCO 0201 style), half-slotted (0200 style)
  or full-overlap (0203 style);
- mode ``telescope``: two half-slotted trays, the lid's inside equal to the base's outside.

Every blank is generated by ``pliego.dieline`` (thickness-compensated: panels are inside + the
board caliper, flaps (W + t)/2 or W + t, slots 2t). The fold program is kinematic (a face tree:
no two folds meet inside the board). FEFCO codes are identifiers only; no catalogue drawing is
used.
"""

import pliego


def PARAM(get, default):
    try:
        return get()
    except NameError:
        return default


mode = str(PARAM(lambda: mode, "slotted"))          # noqa: F821
style = str(PARAM(lambda: style, "regular"))        # noqa: F821
length = float(PARAM(lambda: length, 300.0))        # noqa: F821
width = float(PARAM(lambda: width, 200.0))          # noqa: F821
depth = float(PARAM(lambda: depth, 150.0))          # noqa: F821
lid_depth = float(PARAM(lambda: lid_depth, 50.0))   # noqa: F821
board = str(PARAM(lambda: board, "corrugated-b-flute"))   # noqa: F821
glue = float(PARAM(lambda: glue, 30.0))             # noqa: F821

BOARDS = ("corrugated-e-flute", "corrugated-b-flute", "corrugated-c-flute",
          "corrugated-bc-double-wall")
STYLES = ("regular", "half", "full")
if board not in BOARDS:
    raise ValueError(f"corrugated-shipper: board must be one of {BOARDS}, got {board!r}")
if style not in STYLES:
    raise ValueError(f"corrugated-shipper: style must be one of {STYLES}, got {style!r}")
if mode not in ("slotted", "telescope"):
    raise ValueError(f"corrugated-shipper: unknown mode {mode!r}")
width = min(width, length)                           # the generator wants W ≤ L
glue = pliego.clamp(glue, 20.0, 50.0)

if mode == "telescope":
    base, lid = pliego.dieline.telescope(length, width, depth, min(lid_depth, depth), board,
                                         glue=glue)
    packs = [base, lid]
    title = "Corrugated shipper (telescope)"
else:
    packs = [pliego.dieline.slotted(length, width, depth, board, flaps=style, glue=glue)]
    title = f"Corrugated shipper ({style} slotted)"

result = pliego.dieline.assemble(
    packs, title=title,
    label={"en": "Fold program", "es": "Secuencia de armado", "fr": "Séquence de montage",
           "pt": "Sequência de montagem"},
    meta={"cartridge": "corrugated-shipper",
          "params": {"style": style, "length": length, "width": width, "depth": depth,
                     "lid_depth": lid_depth, "board": board, "glue": glue}})
