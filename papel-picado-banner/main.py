"""Papel picado banner — sheet-hyperobjects cartridge (Pliego).

A string of tissue-paper (papel de china) flags hanging from a sagging line, moved by a `wind`
control. Papel picado is the papercut tradition credited to San Salvador Huixcolotla, Puebla (see
the article for the sources). The motifs here are ORIGINAL geometric designs (flowers, diamonds,
scallops, a sun) generated by this script — no artisan's design is copied.

Each motif is made by fold-and-cut: the flag is folded in half (mirror) or in quarters with simple
folds (`pliego.simplefold`), cut once through every layer (`pliego.foldcut`) and unfolded. The cut
flag is checked with `pliego.papercut.analyze` — one connected piece, every bridge at least the
tissue's minimum feature (1.5 mm, the `papel-de-china` stock card) — and the script refuses to
build otherwise. The flags are then ironed flat (no crease is kept), coloured, and hung: each flag's
top edge (the strip that folds over the string) is pinned along a chord of the catenary
y(x) = y₀ − sag + a·(cosh((x − span/2)/a) − 1), with a solved so the line sags by `sag` mm.
"""

import math

import pliego


def PARAM(get, default):
    try:
        return get()
    except NameError:
        return default


def clamp(value, lo, hi):
    return max(lo, min(hi, float(value)))


MIN_FEATURE = 1.5  # mm, papel-de-china stock card fabrication.min_feature_mm
STOCK = "papel-de-china"
COLOURS = ["#e8336d", "#f28c28", "#f6d32d", "#33a852", "#2a7de1", "#8e44ad"]

flags = int(clamp(PARAM(lambda: flags, 5), 1, 6))
width = clamp(PARAM(lambda: width, 180.0), 120.0, 240.0)
height = clamp(PARAM(lambda: height, 240.0), 160.0, 320.0)
hem = clamp(PARAM(lambda: hem, 20.0), 12.0, 40.0)
gap = clamp(PARAM(lambda: gap, 25.0), 5.0, 120.0)
sag = clamp(PARAM(lambda: sag, 60.0), 5.0, 300.0)
symmetry = int(PARAM(lambda: symmetry, 1))
motifs = str(PARAM(lambda: motifs, "alternate"))
wind = clamp(PARAM(lambda: wind, 2.0), 0.0, 12.0)
if symmetry not in (1, 2):
    raise ValueError("symmetry must be 1 (fold in half) or 2 (fold in quarters)")
if motifs not in ("alternate", "flower", "sun"):
    raise ValueError(f"motifs {motifs!r} must be alternate, flower or sun")

W, H = width, height
CX = W / 2.0
margin = 0.05 * min(W, H) + 2.0
fringe = 0.0 if symmetry == 2 else 0.06 * H     # scallop / zigzag depth at the bottom edge
bottom = hem if symmetry == 2 else fringe + 1.0  # quarters mirror the top strip to the bottom
px0, px1 = margin, W - margin
py0, py1 = bottom + margin, H - hem - margin
CY = (py0 + py1) / 2.0 if symmetry == 1 else H / 2.0
PW, PH = px1 - px0, py1 - py0
if min(PW, PH) < 60.0:
    raise ValueError("the flag leaves less than 60 mm for the motif: enlarge it or lower the hem")


def rot(poly, deg, about):
    c, s = math.cos(math.radians(deg)), math.sin(math.radians(deg))
    return [(about[0] + (x - about[0]) * c - (y - about[1]) * s,
             about[1] + (x - about[0]) * s + (y - about[1]) * c) for x, y in poly]


def diamond(cx, cy, along, across, deg):
    return rot([(cx - along, cy), (cx, cy - across), (cx + along, cy), (cx, cy + across)],
               deg, (cx, cy))


def disc(cx, cy, r, n=12):
    return [(cx + r * math.cos(2 * math.pi * k / n), cy + r * math.sin(2 * math.pi * k / n))
            for k in range(n)]


def petal(cx, cy, r_in, length, wide, deg):
    a = math.radians(deg)
    ring = pliego.papercut.petal((cx + r_in * math.cos(a), cy + r_in * math.sin(a)), length, wide,
                                 deg, segments=6)
    return [(p.x, p.y) for p in ring]


def in_fold(poly):
    """Keep only cuts that reach the folded stack (x ≥ axis; y ≥ CY too for quarters)."""
    return any(x > CX + 1e-6 and (symmetry == 1 or y > CY + 1e-6) for x, y in poly)


def flower_motif():
    r = 0.30 * min(PW, PH)
    r_in = 0.22 * r
    cuts = [petal(CX, CY, r_in, r - r_in, 0.36 * (r - r_in), 45.0 * k) for k in range(8)]
    cuts.append(disc(CX, CY, 0.45 * r_in))
    along, across = max(0.07 * r, 2.5), max(0.035 * r, 1.6)
    ring = r + max(0.1 * r, 3.0) + along
    cuts += [diamond(CX + ring * math.cos(math.radians(22.5 * k)),
                     CY + ring * math.sin(math.radians(22.5 * k)), along, across, 22.5 * k)
             for k in range(16)]
    q = 0.18 * min(PW, PH)
    for sx in (-1, 1):
        for sy in (-1, 1):
            fx, fy = CX + sx * (PW / 2 - q), CY + sy * (PH / 2 - q)
            cuts += [petal(fx, fy, 0.12 * q, 0.7 * q, 0.36 * q, 90.0 * k + 45.0) for k in range(4)]
    return cuts


def sun_motif():
    r = 0.24 * min(PW, PH)
    cuts = [disc(CX, CY, 0.35 * r)]
    for k in range(12):
        a = math.radians(30.0 * k)
        base, tipr, half = 0.55 * r, 1.25 * r, math.radians(8.0)
        cuts.append([(CX + base * math.cos(a - half), CY + base * math.sin(a - half)),
                     (CX + tipr * math.cos(a), CY + tipr * math.sin(a)),
                     (CX + base * math.cos(a + half), CY + base * math.sin(a + half))])
    step = 0.16 * min(PW, PH)
    while True:  # at most 24 lattice diamonds keep the render inside the runner's time budget
        lattice = []
        nx, ny = int(PW / 2 / step), int(PH / 2 / step)
        for i in range(-nx, nx + 1):
            for j in range(-ny, ny + 1):
                x, y = CX + i * step, CY + j * step
                if (i + j) % 2 or math.hypot(x - CX, y - CY) < 1.45 * r:
                    continue
                if abs(x - CX) > PW / 2 - 0.35 * step or abs(y - CY) > PH / 2 - 0.35 * step:
                    continue
                lattice.append(diamond(x, y, 0.32 * step, 0.32 * step, 0.0))
        if len(lattice) <= 24:
            break
        step *= 1.1
    cuts += lattice
    return cuts


def bottom_edge(kind):
    """Cuts that shape the bottom edge in the folded half: scallops or a zigzag fringe."""
    if symmetry == 2:
        return []
    count = max(2, round(W / 2 / 22.0))
    step = (W / 2) / count
    edge = [(CX - 1.0, -1.0), (CX - 1.0, 1.0 + fringe)]
    for k in range(count):
        x0 = CX + k * step
        if kind == "scallop":
            edge += [(x0 + step * t / 6, 1.0 + fringe * (1 - math.sin(math.pi * t / 6)))
                     for t in range(6)]
        else:
            edge += [(x0, 1.0 + fringe), (x0 + step / 2, 1.0)]
    edge += [(W, 1.0 + fringe), (W + 1.0, 1.0 + fringe), (W + 1.0, -1.0)]
    return [edge]


def cut_flag(kind):
    """Fold, cut through every layer, unfold; returns (outline, holes, report, folded cut)."""
    state = pliego.simplefold.FoldedState(pliego.rectangle(W, H))
    state.fold(((CX, 0.0), (CX, H)), "valley")
    if symmetry == 2:
        state.fold(((W, H / 2), (CX, H / 2)), "valley")
    motif = flower_motif() if kind == "flower" else sun_motif()
    regions = [p for p in motif if in_fold(p)]
    regions += bottom_edge("scallop" if kind == "flower" else "zigzag")
    res = pliego.foldcut.cut(state, regions, id=f"motif-{kind}", stock=STOCK)
    if not res.connected:
        raise ValueError(f"{kind} motif: the cut leaves {len(res.islands)} loose pieces")
    rep = pliego.papercut.analyze(res.sheet, min_feature_mm=MIN_FEATURE)
    if not rep.ok:
        raise ValueError(f"{kind} motif fails the papercut check: "
                         + "; ".join(i["detail"] for i in rep.issues if i["level"] == "error"))
    floor = max(1.0, MIN_FEATURE ** 2)  # spec §5.7: the face floor is min_feature_mm²
    arr = res.sheet.build()
    smallest = min(abs(pliego.polygon_area([arr.vertices[v] for v in f])) for f in arr.faces)
    if smallest < floor:
        raise ValueError(f"{kind} motif: a mesh face of {smallest:.2f} mm² is below the "
                         f"{floor:.2f} mm² floor; change the flag size or proportions")
    outline = [(p.x, p.y) for p in res.sheet.outline]
    holes = [[(p.x, p.y) for p in h] for h in res.sheet.holes]
    return outline, holes, rep


kinds = {"alternate": ["flower", "sun"], "flower": ["flower"], "sun": ["sun"]}[motifs]
cuts = {k: cut_flag(k) for k in kinds}

# ── the line: a catenary through two posts, sagging by `sag` at mid-span ──
span = flags * W + (flags + 1) * gap
y0 = H + sag + 300.0  # post height: the flags hang clear of the ground plane


def sag_of(a):
    return a * (math.cosh(span / (2.0 * a)) - 1.0)


lo, hi = span / 1400.0, span * 1e4   # sag_of falls monotonically in a
for _ in range(200):
    mid = math.sqrt(lo * hi)
    lo, hi = (mid, hi) if sag_of(mid) > sag else (lo, mid)
A = math.sqrt(lo * hi)


def line_y(x):
    return y0 - sag + A * (math.cosh((x - span / 2.0) / A) - 1.0)


def chord_end(x_start):
    """x where the chord from the catenary point at x_start has length W (bisection)."""
    ys = line_y(x_start)
    lo_, hi_ = x_start, x_start + W
    for _ in range(80):
        m = (lo_ + hi_) / 2.0
        if math.hypot(m - x_start, line_y(m) - ys) < W:
            lo_ = m
        else:
            hi_ = m
    return (lo_ + hi_) / 2.0


sheets, joins = [], []
names = {"flower": ("flower", "flor", "fleur", "flor"), "sun": ("sun", "sol", "soleil", "sol")}
x = gap
for k in range(flags):
    kind = kinds[k % len(kinds)]
    outline, holes, _ = cuts[kind]
    x_end = chord_end(x)
    p0, p1 = (x, line_y(x)), (x_end, line_y(x_end))
    beta = math.atan2(p1[1] - p0[1], p1[0] - p0[0])
    # rotation: +90° about x (sheet stands up, front faces +z), then β about z (follow the chord)
    sx = cx = math.sqrt(0.5)
    sz, cz = math.sin(beta / 2.0), math.cos(beta / 2.0)
    quat = (cz * sx, sz * sx, cx * sz, cz * cx)
    top_left = (-H * math.sin(beta), H * math.cos(beta), 0.0)  # local (0, H) after the rotation
    origin = (p0[0] - top_left[0], p0[1] - top_left[1], 0.0)
    colour = COLOURS[k % len(COLOURS)]
    n = names[kind]
    sheet = pliego.Sheet(
        f"flag-{k + 1}", outline, stock=STOCK, grain_deg=90.0,
        label={"en": f"Flag {k + 1} ({n[0]})", "es": f"Banderita {k + 1} ({n[1]})",
               "fr": f"Fanion {k + 1} ({n[2]})", "pt": f"Bandeirinha {k + 1} ({n[3]})"},
        front=colour, back=colour,
        placement=pliego.Placement(origin=origin, rotation=quat))
    for h in holes:
        sheet.hole(h)
    sheets.append(sheet)
    joins.append(pliego.pin(f"hang-{k + 1}", along=(sheet, [(0.0, H), (W, H)])))
    x = x_end + gap

wind_control = pliego.control("wind", "wind", {"en": "Wind", "es": "Viento", "fr": "Vent",
                                               "pt": "Vento"}, wind, 0.0, 12.0, "m/s")
result = pliego.Assembly(sheets, joins=joins, controls=[wind_control],
                         title="Papel picado banner", meta={"min_feature_mm": MIN_FEATURE})
