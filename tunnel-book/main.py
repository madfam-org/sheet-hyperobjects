"""Tunnel book — sheet-hyperobjects cartridge (Pliego).

A tunnel (peepshow) book cut from ONE sheet: `layers` frames stand one behind the other — a front
cover with a window, middle frames with cut scenes, a solid back scene — held by accordion side
walls and opened by pulling the cover.

Original MADFAM construction, chosen so that the opening is a pure fold program:

* the frames sit in one column of the sheet, the back scene at the bottom, the cover at the top;
  consecutive frames are linked by a narrow strap at their top or bottom edge (alternately), so
  the frames form one chain of hinges and each frame shows the opposite face of the sheet;
* every frame except the back carries its two side walls, hinged at its side edges; each wall has
  a peak fold in the middle (the accordion) and ends in a glue tab that is glued to the side
  margin of the next frame — the only glue in the book, and it closes the loops;
* walls and straps fold inward with the same angle φ: hinge 90° + φ, peak 2φ, tab 90° + φ, so
  every crease angle is affine in φ and every in-between state of the program is exact. The
  initial frame is the closed book (frames 3 mm apart); the program pulls it open to φ = 30°.

Scenes (`scene`) are generated by this script from simple shapes (fir trees, waves and a boat,
a skyline, mountain ridges): each windowed frame keeps a silhouette that grows from its bottom
margin (and, on some covers, hangs from its top margin), deeper layers sitting higher. Every
frame is checked with `pliego.papercut.analyze` against the stock's minimum feature (fail loud),
the glue welds are checked at every state of the program, and the open state is checked
(parallel frames, spacing, alignment).
"""

