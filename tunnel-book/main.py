T = pliego.clamp(0.3 * D, 8.0, 14.0)                   # glue tab width
TAPER = 3.0
MS = max(T + 3.0, D / 4.0 + 3.0)                       # side margin (tab zone, wall V)
MV = max(10.0, D / 4.0 + 3.0)                          # top and bottom margin (strap V)
