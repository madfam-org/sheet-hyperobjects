# ── self-checks (fail loud) ──
TOL = 1e-4                           # mm; the arrangement snaps vertices to a fine grid
def world(tr, u, v):
    rm, t = tr
    p = (u, 0.0, -v)
    return tuple(rm[k][0] * p[0] + rm[k][1] * p[1] + rm[k][2] * p[2] + t[k] for k in range(3))


def face_at(u, v):
    return pliego.kinematics.root_face(arr, pliego.Vec2(u, v))


root = face_at(W / 2, H / 2)
for r, local in holes.items():
    probe = pliego.Sheet(f"frame-{N - r}", [(0, 0), (W, 0), (W, H), (0, H)], stock=stock)
    probe.hole(local)
    rep = pliego.papercut.analyze(probe, min_feature_mm=MINF)
    if not rep.ok or rep.components != 1:
        raise ValueError(f"tunnel-book: frame {N - r} fails the papercut check: "
                         + "; ".join(i["detail"] for i in rep.issues if i["level"] == "error"))
    holes[r] = (local, rep.min_bridge_mm)
worst = 0.0
for k in range(5):
    phi = CLOSED + (OPEN - CLOSED) * k / 4.0
    tr = pliego.kinematics.face_transforms(arr, angles_at(phi), root)
    if any(t is None for t in tr):
        raise ValueError("tunnel-book: the net is not one hinged piece")
    for jid, region, mp in glues:
        for u, v in region:
            q = (mp[0] * u + mp[1] * v + mp[4], mp[2] * u + mp[3] * v + mp[5])
