creases = []                                   # (mark, role, sign)


def fold(a, b, role, sign, name):
    mag = 90.0 + OPEN if role != "peak" else 2.0 * OPEN
    kind = "valley" if (sign > 0) == (role != "peak") else "mountain"
    m = sheet.crease(a, b, kind, mag, treatment="score", name=name)
    creases.append((m, role, sign))
    return m


for g in range(N - 1):
    sign = 1 if g % 2 == 0 else -1
    yb, ya = Y(g) + H, Y(g + 1)
    xl, xr = W / 2 - B / 2, W / 2 + B / 2
    fold((xl, yb), (xr, yb), "hinge", sign, "strap-fold")
    fold((xl, yb + D / 2), (xr, yb + D / 2), "peak", sign, "strap-peak")
    fold((xl, ya), (xr, ya), "hinge", sign, "strap-fold")
    for xh, xp, xt in ((0.0, -D / 2, -D), (W, W + D / 2, W + D)):
        fold((xh, ya), (xh, ya + H), "hinge", sign, "wall-fold")
        fold((xp, ya), (xp, ya + H), "peak", sign, "wall-peak")
        fold((xt, ya), (xt, ya + H), "hinge", sign, "glue-tab")
sheet.label_edge("cover-edge", (0.0, Y(N - 1) + H), (W, Y(N - 1) + H))   # where you pull
sheet.label_edge("back-zone", (0.0, 0.0), (0.0, H))      # the back scene's glue zones (sides)
sheet.label_edge("back-zone", (W, 0.0), (W, H))


def angles_at(phi):
    out = {}
    for m, role, sign in creases:
        a = sign * (90.0 + phi) if role == "hinge" else -sign * 2.0 * phi
        for e in m.edges():
            out[e] = a
    return out


# ── glue: each wall's tab onto the side margin of the frame behind ──
joins, glues = [], []
for g in range(N - 1):
    ya, yb = Y(g + 1), Y(g)
    i = 0.5
    for side, x_in, x_out, tx in (("left", -D - i, -D - T + i, -D),
                                  ("right", W + D + i, W + D + T - i, 2 * W + D)):
        lo, hi = min(x_in, x_out), max(x_in, x_out)
        region = [(lo, ya + TAPER + i), (hi, ya + TAPER + i), (hi, ya + H - TAPER - i),
                  (lo, ya + H - TAPER - i)]
        mp = (-1.0, 0.0, 0.0, -1.0, tx, ya + yb + H)
        face = "front" if upright(g) else "back"
        jid = f"tab-{N - g - 1}-{side}"
        joins.append(pliego.glue(jid, sheet, region, sheet, mp, face))
        glues.append((jid, region, mp))

