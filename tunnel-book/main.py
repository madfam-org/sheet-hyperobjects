MINF = MIN_FEATURE[stock]
N = layers
W = pliego.clamp(frame_width, 80.0, 240.0)
H = pliego.clamp(frame_height, 60.0, 180.0)
OPEN = 30.0                          # φ when displayed: walls and straps keep a shallow V
CLOSED_PITCH = 3.0                   # frame spacing of the closed book (paper thickness)
